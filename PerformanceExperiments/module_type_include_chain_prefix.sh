#!/usr/bin/env bash
# Prefix-style chain of module types: stage k is a functor over the
# whole chain built so far, and extends it by one interface:
#   Module Type I_k (Import a : A_{k-1}). ... End I_k.
#   Module Type A_k := A_{k-1} <+ I_k.
# Every stage re-checks all previous fields, so there are quadratically
# many field subtype checks in total; each stage command is timed
# separately (Params: n=k is the stage number). Prefix variant of the
# shape of https://github.com/rocq-prover/rocq/issues/22279.
set -e
size="$1"
case "$size" in
    Sanity)    max=2;;
    SuperFast) max=50;;
    Fast)      max=150;;
    Medium)    max=300;;
    Slow)      max=600;;
    VerySlow)  max=1000;;
    *) echo "Invalid size '$size'" >&2; exit 1;;
esac
echo "(* Autogenerated by module_type_include_chain_prefix.sh $size *)"
echo "Module Type I_0. Parameter t_0 : Type. End I_0."
echo "Module Type A_0 := I_0."
for k in $(seq 1 "$max"); do
    km1=$((k-1))
    echo "Module Type I_${k} (Import a : A_${km1}). Parameter t_${k} : Type. End I_${k}."
    echo "Goal True. Proof. idtac \"Params: n=${k}\". Abort."
    echo "Time Module Type A_${k} := A_${km1} <+ I_${k}."
done
