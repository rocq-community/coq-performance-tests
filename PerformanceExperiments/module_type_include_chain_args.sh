#!/usr/bin/env bash
# Chained inclusion of n module types, each a functor over the same
# shared nonempty parameter signature (with a definitional field, so
# each subtyping check involves a conversion):
# Module Type Chain := Args <+ I1 <+ I2 <+ ... <+ In.
# Nonempty-Args variant of the shape of
# https://github.com/rocq-prover/rocq/issues/22279.
set -e
size="$1"
case "$size" in
    Sanity)    ns="2";;
    SuperFast) ns="5 10 25 50 100";;
    Fast)      ns="150 200 300 400";;
    Medium)    ns="500 650 800";;
    Slow)      ns="1000 1300 1600";;
    VerySlow)  ns="2000 2600 3200";;
    *) echo "Invalid size '$size'" >&2; exit 1;;
esac
echo "(* Autogenerated by module_type_include_chain_args.sh $size *)"
for n in $ns; do
    echo "Module Type Args_${n}."
    echo "  Parameter t : Type."
    echo "  Parameter op : t -> t."
    echo "  Parameter e : t."
    echo "  Definition twice := op (op e)."
    echo "End Args_${n}."
    for i in $(seq 1 "$n"); do
        echo "Module Type I_${n}_${i} (Import a : Args_${n})."
        echo "  Parameter f_${n}_${i} : t -> t."
        echo "  Parameter x_${n}_${i} : t."
        echo "End I_${n}_${i}."
    done
    echo "Goal True. Proof. idtac \"Params: n=${n}\". Abort."
    printf 'Time Module Type Chain_%s := Args_%s' "$n" "$n"
    for i in $(seq 1 "$n"); do printf ' <+ I_%s_%s' "$n" "$i"; done
    echo "."
done
